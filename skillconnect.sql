DROP DATABASE IF EXISTS skillconnect;
CREATE DATABASE skillconnect;
USE skillconnect;

-- =========================================================
-- BAGIAN 1: STRUKTUR TABEL (DDL)
-- Urutan: tabel induk dulu, baru tabel anak (yang punya FK)
-- =========================================================

-- 1. users : semua akun (admin, mahasiswa, client)
CREATE TABLE users (
    id_user     INT AUTO_INCREMENT PRIMARY KEY,
    nama        VARCHAR(100) NOT NULL,
    email       VARCHAR(100) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    role        ENUM('admin', 'mahasiswa', 'client') NOT NULL,
    no_hp       VARCHAR(15),
    status_akun ENUM('aktif', 'nonaktif') NOT NULL DEFAULT 'aktif',
    created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. mahasiswa : detail akun ber-role mahasiswa (relasi 1:1 ke users)
CREATE TABLE mahasiswa (
    id_mahasiswa INT PRIMARY KEY,
    nim          VARCHAR(20) NOT NULL UNIQUE,
    universitas  VARCHAR(100) NOT NULL,
    jurusan      VARCHAR(100) NOT NULL,
    bio          TEXT,
    FOREIGN KEY (id_mahasiswa) REFERENCES users(id_user) ON DELETE CASCADE
);

-- 3. client : detail akun ber-role client (relasi 1:1 ke users)
CREATE TABLE client (
    id_client     INT PRIMARY KEY,
    tipe_client   ENUM('UMKM', 'Organisasi', 'Event Organizer', 'Individu', 'Komunitas') NOT NULL,
    nama_instansi VARCHAR(100),
    alamat        VARCHAR(255),
    FOREIGN KEY (id_client) REFERENCES users(id_user) ON DELETE CASCADE
);

-- 4. kategori : kategori pekerjaan (dikelola admin)
CREATE TABLE kategori (
    id_kategori   INT AUTO_INCREMENT PRIMARY KEY,
    nama_kategori VARCHAR(50) NOT NULL UNIQUE
);

-- 5. skill : daftar skill, tiap skill masuk satu kategori
CREATE TABLE skill (
    id_skill    INT AUTO_INCREMENT PRIMARY KEY,
    id_kategori INT NOT NULL,
    nama_skill  VARCHAR(50) NOT NULL UNIQUE,
    FOREIGN KEY (id_kategori) REFERENCES kategori(id_kategori)
);

-- 6. mahasiswa_skill : tabel penghubung M:N mahasiswa <-> skill
CREATE TABLE mahasiswa_skill (
    id_mahasiswa INT NOT NULL,
    id_skill     INT NOT NULL,
    level        ENUM('pemula', 'menengah', 'mahir') NOT NULL DEFAULT 'pemula',
    PRIMARY KEY (id_mahasiswa, id_skill),
    FOREIGN KEY (id_mahasiswa) REFERENCES mahasiswa(id_mahasiswa) ON DELETE CASCADE,
    FOREIGN KEY (id_skill) REFERENCES skill(id_skill)
);

-- 7. portfolio : hasil karya mahasiswa (1 mahasiswa banyak portfolio)
CREATE TABLE portfolio (
    id_portfolio INT AUTO_INCREMENT PRIMARY KEY,
    id_mahasiswa INT NOT NULL,
    judul        VARCHAR(100) NOT NULL,
    deskripsi    TEXT,
    link         VARCHAR(255),
    tahun        YEAR,
    FOREIGN KEY (id_mahasiswa) REFERENCES mahasiswa(id_mahasiswa) ON DELETE CASCADE
);

-- 8. job : lowongan yang diposting client
CREATE TABLE job (
    id_job      INT AUTO_INCREMENT PRIMARY KEY,
    id_client   INT NOT NULL,
    id_kategori INT NOT NULL,
    judul       VARCHAR(150) NOT NULL,
    deskripsi   TEXT,
    budget      DECIMAL(12,2) NOT NULL CHECK (budget > 0),
    deadline    DATE NOT NULL,
    status      ENUM('open', 'in_progress', 'completed', 'cancelled') NOT NULL DEFAULT 'open',
    created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_client) REFERENCES client(id_client),
    FOREIGN KEY (id_kategori) REFERENCES kategori(id_kategori)
);

-- 9. job_skill : tabel penghubung M:N job <-> skill yang dibutuhkan
CREATE TABLE job_skill (
    id_job   INT NOT NULL,
    id_skill INT NOT NULL,
    PRIMARY KEY (id_job, id_skill),
    FOREIGN KEY (id_job) REFERENCES job(id_job) ON DELETE CASCADE,
    FOREIGN KEY (id_skill) REFERENCES skill(id_skill)
);

-- 10. lamaran : mahasiswa apply ke job (1 mahasiswa hanya 1x per job)
CREATE TABLE lamaran (
    id_lamaran    INT AUTO_INCREMENT PRIMARY KEY,
    id_job        INT NOT NULL,
    id_mahasiswa  INT NOT NULL,
    harga_tawaran DECIMAL(12,2) NOT NULL,
    pesan_lamaran TEXT,
    status        ENUM('pending', 'diterima', 'ditolak') NOT NULL DEFAULT 'pending',
    tanggal_lamar DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_job, id_mahasiswa),
    FOREIGN KEY (id_job) REFERENCES job(id_job),
    FOREIGN KEY (id_mahasiswa) REFERENCES mahasiswa(id_mahasiswa)
);

-- 11. proyek : kontrak kerja dari lamaran yang diterima (1 lamaran = 1 proyek)
CREATE TABLE proyek (
    id_proyek   INT AUTO_INCREMENT PRIMARY KEY,
    id_lamaran  INT NOT NULL UNIQUE,
    harga_deal  DECIMAL(12,2) NOT NULL,
    tgl_mulai   DATE NOT NULL,
    tgl_selesai DATE,
    status      ENUM('berjalan', 'selesai', 'batal') NOT NULL DEFAULT 'berjalan',
    FOREIGN KEY (id_lamaran) REFERENCES lamaran(id_lamaran)
);

-- 12. pesan : chat antara client dan mahasiswa tentang sebuah job
CREATE TABLE pesan (
    id_pesan    INT AUTO_INCREMENT PRIMARY KEY,
    id_job      INT NOT NULL,
    id_pengirim INT NOT NULL,
    id_penerima INT NOT NULL,
    isi_pesan   TEXT NOT NULL,
    waktu_kirim DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_job) REFERENCES job(id_job),
    FOREIGN KEY (id_pengirim) REFERENCES users(id_user),
    FOREIGN KEY (id_penerima) REFERENCES users(id_user)
);

-- 13. pembayaran : pembayaran client untuk sebuah proyek
CREATE TABLE pembayaran (
    id_pembayaran INT AUTO_INCREMENT PRIMARY KEY,
    id_proyek     INT NOT NULL,
    jumlah        DECIMAL(12,2) NOT NULL CHECK (jumlah > 0),
    metode        ENUM('transfer', 'e-wallet') NOT NULL,
    status        ENUM('pending', 'lunas', 'gagal') NOT NULL DEFAULT 'pending',
    tanggal_bayar DATETIME,
    FOREIGN KEY (id_proyek) REFERENCES proyek(id_proyek)
);

-- 14. review : rating dua arah setelah proyek selesai
CREATE TABLE review (
    id_review      INT AUTO_INCREMENT PRIMARY KEY,
    id_proyek      INT NOT NULL,
    id_pemberi     INT NOT NULL,
    id_penerima    INT NOT NULL,
    rating         TINYINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    komentar       TEXT,
    tanggal_review DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_proyek, id_pemberi),
    FOREIGN KEY (id_proyek) REFERENCES proyek(id_proyek),
    FOREIGN KEY (id_pemberi) REFERENCES users(id_user),
    FOREIGN KEY (id_penerima) REFERENCES users(id_user)
);

